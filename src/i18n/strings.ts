const dict: Record<Language, Record<StringKey, string>> = { en, he };

export function translate(lang: Language, key: StringKey, vars?: Record<string, string | number>): string {
  let s = dict[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const localeFor = (lang: Language) => (lang === 'he' ? 'he-IL' : 'en-GB');
export const dirFor = (lang: Language) => (lang === 'he' ? 'rtl' : 'ltr');

/** "15 min", "1 h", "2 d" */
export function formatDuration(lang: Language, minutes: number): string {
  if (minutes % 1440 === 0 && minutes >= 1440) return translate(lang, 'days', { n: minutes / 1440 });
  if (minutes % 60 === 0 && minutes >= 60) return translate(lang, 'hours', { n: minutes / 60 });
  return translate(lang, 'min', { n: minutes });
}

export function formatRemindBefore(lang: Language, minutes: number): string {
  if (minutes === 0) return translate(lang, 'remindAtStart');
  const [n, unit] =
    minutes % 43200 === 0
      ? [minutes / 43200, 'mo']
      : minutes % 10080 === 0
        ? [minutes / 10080, 'w']
        : minutes % 1440 === 0
          ? [minutes / 1440, 'd']
          : minutes % 60 === 0
            ? [minutes / 60, 'h']
            : [minutes, 'm'];
  if (lang === 'he') {
    const he = { mo: n === 1 ? 'חודש' : 'חודשים', w: n === 1 ? 'שבוע' : 'שבועות', d: n === 1 ? 'יום' : 'ימים', h: n === 1 ? 'שעה' : 'שעות', m: 'דק׳' }[unit as 'w'];
    return n === 1 && unit !== 'm' ? `${he} לפני` : `${n} ${he} לפני`;
  }
  const en = { mo: 'month', w: 'week', d: 'day', h: 'hour', m: 'min' }[unit as 'w'];
  return `${n} ${en}${n === 1 || unit === 'm' ? '' : 's'} before`;
}
